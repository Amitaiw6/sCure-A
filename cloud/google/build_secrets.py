"""Write Secrets.gs for the Apps Script project from cloud/portal_secrets.local.txt (git-ignored).

    python cloud/google/build_secrets.py

Secrets.gs is the fallback the script uses when the Apps Script project has no
PORTAL_PASSWORD / MACHINE_KEYS / DVT_KEY script properties set. Everything else in
cloud/google/ is edited by hand: Page.html IS the portal page (it used to be generated
from the Fly portal cloud/portal.py, which was deleted with the Fly account in 2026-10).
"""
import json
import pathlib
import re
import secrets as secretslib

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE.parent / 'portal_secrets.local.txt'
OUT = HERE / 'Secrets.gs'


def main():
    if not SRC.exists():
        raise SystemExit(f'no {SRC.name} - set PORTAL_PASSWORD / MACHINE_KEYS / DVT_KEY as script properties instead')
    text = SRC.read_text(encoding='utf-8')
    pw = re.search(r'portal password:\s*(\S+)', text)
    keys = dict(re.findall(r'machine key \(([^)]+)\):\s*(\S+)', text))
    dvt = re.search(r'dvt key:\s*(\S+)', text)
    if not dvt:                     # first run: mint one and remember it next to the machine keys
        key = secretslib.token_urlsafe(24)
        SRC.write_text(text.rstrip('\n') + f'\ndvt key: {key}\n', encoding='utf-8')
        print(f'added a DVT key to {SRC.name} - paste it into the DVT tool\'s Cloud box')
    else:
        key = dvt.group(1)
    # NetBird (read-only status of each CureBox on the mesh): a management-API token and which peer name each CureBox has
    nb = re.search(r'netbird token:\s*(\S+)', text)
    peers = dict(re.findall(r'netbird peer \(([^)]+)\):\s*(\S+)', text))
    OUT.write_text('// Generated by build_secrets.py from cloud/portal_secrets.local.txt - DO NOT COMMIT (git-ignored)\n'
                   f'var SECRETS = {json.dumps({"password": pw.group(1) if pw else "", "machineKeys": keys, "dvtKey": key, "netbirdToken": nb.group(1) if nb else "", "netbirdPeers": peers})};\n',
                   encoding='utf-8')
    print(f'wrote {OUT.name} ({len(keys)} machine key(s) + the DVT key{" + the NetBird token" if nb else ""}, {len(peers)} NetBird peer name(s))')


if __name__ == '__main__':
    main()
