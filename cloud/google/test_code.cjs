function makeSheet(name) {
  const rows = [];
  const cell = (r, c) => (rows[r - 1] || [])[c - 1] ?? '';
  return {
    name, rows,
    getLastRow: () => rows.length,
    getLastColumn: () => rows.reduce((m, r) => Math.max(m, r.length), 0),
    setFrozenRows() {},
    appendRow(v) { rows.push(v.slice()); },
    deleteRow(r) { rows.splice(r - 1, 1); },
    deleteRows(r, n) { rows.splice(r - 1, n); },
    insertColumnBefore(c) { rows.forEach(r => { while (r.length < c - 1) r.push(''); r.splice(c - 1, 0, ''); }); },
    getRange(r, c, nr = 1, nc = 1) {
      return {
        getValues: () => Array.from({ length: nr }, (_, i) => Array.from({ length: nc }, (_, j) => cell(r + i, c + j))),
        setValues(vals) { vals.forEach((row, i) => row.forEach((v, j) => { rows[r + i - 1] = rows[r + i - 1] || []; rows[r + i - 1][c + j - 1] = v; })); },
        setValue(v) { rows[r - 1] = rows[r - 1] || []; rows[r - 1][c - 1] = v; },
      };
    },
  };
}
