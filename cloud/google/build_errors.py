"""Write ErrorRegistry.gs for the Apps Script portal from an errors.json (titles + repair-video links per code).

    python cloud/google/build_errors.py [path/to/errors.json]

Default source: the firmware's master registry, ../sCureBox-CS/config/errors.json next to this repo, else
public/config/errors.json. The service team edits titles and videos with tools/error-editor.html, saves errors.json,
then runs this script and `clasp push` + deploy - the portal's "Errors today" then shows the new title and a
"Video" link per code. ErrorRegistry.gs holds no secrets and is committed.
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parent.parent
CANDIDATES = [REPO.parent / 'sCureBox-CS' / 'config' / 'errors.json', REPO / 'public' / 'config' / 'errors.json']
OUT = HERE / 'ErrorRegistry.gs'


def main():
    src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else next((p for p in CANDIDATES if p.exists()), None)
    if src is None or not src.exists():
        raise SystemExit(f'no errors.json (tried {", ".join(map(str, CANDIDATES))})')
    data = json.loads(src.read_text(encoding='utf-8'))
    reg = {}
    for e in data.get('errors', []):
        entry = {'t': str(e.get('message') or e.get('title') or '').strip()}
        video = str(e.get('videoUrl') or '').strip()
        if video.lower().startswith(('https://', 'http://')):
            entry['v'] = video
        reg[str(e['code'])] = entry
    version = data.get('_meta', {}).get('version', '')
    OUT.write_text('// Generated by build_errors.py from errors.json - edit the titles / videos there (tools/error-editor.html), not here\n'
                   f'var ERROR_REGISTRY = {json.dumps({"version": version, "codes": reg}, ensure_ascii=False, separators=(",", ":"))};\n',
                   encoding='utf-8', newline='\n')
    videos = sum(1 for v in reg.values() if 'v' in v)
    print(f'wrote {OUT.name} from {src}: {len(reg)} codes, {videos} with a video (registry {version})')


if __name__ == '__main__':
    main()
