"""Regenerate dvt-catalog.js (the data behind dvt-tool.html) from the DVT catalog.

    python DVT/web/build_dvt_web.py          # write dvt-catalog.js
    python DVT/web/build_dvt_web.py --check  # exit 1 when dvt-catalog.js is stale

The catalog is loaded through dvt_tool.catalog, so the web page gets exactly the
validation and Hebrew overlay the console applies.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DVT = HERE.parent
sys.path.insert(0, str(DVT))

from dvt_tool.catalog import Catalog  # noqa: E402

CATALOG = DVT / "catalog" / "DVT_test_catalog.yaml"
OUT = HERE / "dvt-catalog.js"

TEST_KEYS = ("test_id", "group", "after_all", "title", "subsystem", "method", "purpose", "applicability", "sample_rationale",
             "safety_critical", "safety_plan", "equipment", "preconditions", "procedure_steps", "data_fields",
             "pass_criteria", "repetitions", "duration_est_min", "dependencies", "sweep", "case_matrix", "uv_wavelength_nm",
             "external_heat")


def build() -> str:
    en = Catalog.load(CATALOG, "en")
    he = Catalog.load(CATALOG, "he")
    tests = {}
    for tid in en.ordered_test_ids():
        t = {k: en.tests[tid].get(k) for k in TEST_KEYS}
        t["pass_criteria"] = " ".join(str(t["pass_criteria"]).split())
        t["variants"] = en.variants(tid)
        t["units"] = en.applicable_units(tid)
        h = he.tests[tid]
        t["he"] = {
            "title": h.get("title"), "purpose": h.get("purpose"), "sample_rationale": h.get("sample_rationale"),
            "safety_plan": h.get("safety_plan"), "preconditions": h.get("preconditions"),
            "steps": [s.get("step") for s in h.get("procedure_steps") or []],
            "equipment": [Catalog.equipment_label(e) for e in h.get("equipment") or []],
            "cases": [c.get("description") for c in h.get("case_matrix") or []],
            "notes": {f["name"]: f.get("note") for f in h.get("data_fields") or [] if f.get("note")},
        }
        tests[tid] = t
    phases = []
    for p_en, p_he in zip(sorted(en.phases, key=lambda p: p["id"]), sorted(he.phases, key=lambda p: p["id"])):
        if p_en.get("tests"):
            phases.append({"id": p_en["id"], "name": p_en["name"], "gate": p_en.get("gate"), "tests": p_en["tests"],
                           "he": {"name": p_he.get("name"), "gate": p_he.get("gate")}})
    units = [{**u, "he": {"notes": uh.get("notes"), "role": uh.get("role_label")}} for u, uh in zip(en.units, he.units)]
    data = {"catalog_version": en.version, "source": "DVT/catalog/DVT_test_catalog.yaml", "runs": en.run_count(),
            "thresholds": en.thresholds, "units": units, "phases": phases, "tests": tests,
            "labels_he": he.labels, "test_renames": en.renames or None}
    body = json.dumps(data, ensure_ascii=False, indent=1, default=str)
    return ("// Generated by build_dvt_web.py from DVT/catalog/DVT_test_catalog.yaml (+ .he.yaml) - do not edit.\n"
            f"window.SCURE_DVT = {body};\n")


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.name} is stale - run: python DVT/web/build_dvt_web.py")
            return 1
        print(f"{OUT.name} is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(text) // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
