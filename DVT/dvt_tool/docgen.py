"""Campaign document — everything in one file (SRS-DVT-197).

One HTML document, printed to PDF with the installed Chrome / Edge (headless),
in the console's language (Hebrew is right-to-left; identifiers stay LTR):

    cover · contents · units · phases, gates and bench order · thresholds
    (CONFIRM where still null) · campaign status (progress, verdict matrix,
    NCRs, waivers, temperature by component) · every test in bench order
    with its process figure, purpose, safety plan, equipment, preconditions,
    procedure with the fields each step records, data fields, pass criteria,
    the CONFIRM lines from the catalog and the runs recorded so far · the
    list of every open CONFIRM item.

    python -m dvt_tool.docgen [--lang he] [--out DIR]
"""

