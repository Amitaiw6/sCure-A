BROWSERS = [
    r"C:\Program Files\Google\Chrome\Application\chrome.exe",
    r"C:\Program Files (x86)\Google\Chrome\Application\chrome.exe",
    os.path.expandvars(r"%LOCALAPPDATA%\Google\Chrome\Application\chrome.exe"),
    r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe",
    r"C:\Program Files\Microsoft\Edge\Application\msedge.exe",
    "/usr/bin/google-chrome", "/usr/bin/chromium", "/usr/bin/chromium-browser",
]


def find_browser() -> str | None:
    for p in BROWSERS:
        if p and Path(p).exists():
            return p
    return None


def confirm_items(catalog_path: str | Path | None) -> dict[str, list[str]]:
    """CONFIRM lines of the catalog, per test (the header block is keyed '')."""
    out: dict[str, list[str]] = {}
    if not catalog_path or not Path(catalog_path).exists():
        return out
    key = ""; carry = False
    for line in Path(catalog_path).read_text(encoding="utf-8").splitlines():
        m = re.match(r"^- test_id:\s*(DVT-[A-Z]{3}-\d{3})", line)
        if m:
            key = m.group(1); carry = False; continue
        is_comment = bool(re.match(r"^\s*#", line))
        if "CONFIRM" in line:
            txt = re.sub(r"^\s*(#\s*)?", "", line).strip()
            out.setdefault(key, []).append(txt)
            carry = is_comment                      # a comment paragraph may continue on the next lines
        elif carry and is_comment and line.strip("# ").strip():
            out[key][-1] += " " + line.strip().lstrip("#").strip()      # continuation of the CONFIRM paragraph
        else:
            carry = False
    return out


def _e(s) -> str:
    return html.escape("" if s is None else str(s), quote=True)


def _ltr(s) -> str:
    return f'<span dir="ltr">{_e(s)}</span>'


class DocBuilder:
    def __init__(self, cat, store, campaign: str = "sCure-DVT"):
        self.cat, self.store, self.campaign = cat, store, campaign
        from .engine import Engine
        self.eng = Engine(cat, store)

    # ------------------------------------------------------------------ pieces
    def _table(self, header: list[str], rows: list[list], cls: str = "") -> str:
        h = "".join(f"<th>{c}</th>" for c in header)
        b = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
        return f'<table class="{cls}"><thead><tr>{h}</tr></thead><tbody>{b}</tbody></table>'

    def _cover(self) -> str:
        runs = self.cat.runs(); prog = self.eng.progress()
        return f"""
<section class="cover">
  <div class="brand">sCure / CureBox</div>
  <h1>{_e(tr("DVT campaign document"))}</h1>
  <div class="sub">{_e(self.campaign)} · {_e(tr("Catalog version"))} {_ltr(self.cat.version)} · {_e(tr("Exported"))} {_ltr(datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"))}</div>
  <div class="kpis">
    <div><b>{len(self.cat.tests)}</b><span>{_e(tr("Tests"))}</span></div>
    <div><b>{len(runs)}</b><span>{_e(tr("Runs"))}</span></div>
    <div><b>{len(self.cat.units)}</b><span>{_e(tr("Units under test"))}</span></div>
    <div><b>{prog['done']}</b><span>{_e(tr("Runs done"))}</span></div>
    <div><b>{prog['PASS']} / {prog['FAIL']}</b><span>PASS / FAIL</span></div>
  </div>
  <div class="foot">{_e(tr("Generated by the sCure DVT console"))} · SRS-DVT-SW Rev B</div>
</section>"""

    def _contents(self) -> str:
        from . import bench
        items = []
        for p in sorted(self.cat.phases, key=lambda p: p["id"]):
            if not p.get("tests"): continue
            items.append(f'<li class="ph">{_e(tr("Phase"))} {p["id"]} — {_e(p["name"])}<ol>' +
                         "".join(f'<li><a href="#{t}">{_ltr(t)}</a> {_e(self.cat.tests[t]["title"])}</li>' for t in bench.bench_order(self.cat, p)) + "</ol></li>")
        return f'<section><h2>{_e(tr("Contents"))}</h2><ol class="toc">{"".join(items)}</ol></section>'

    def _units(self) -> str:
        frozen = {u["unit_id"]: u for u in self.store.units()}
        rows = [[_ltr(u["id"]), _e(u.get("role_label") or u.get("role") or ""), _e(u.get("notes") or ""),
                 _e(tr("yes") if frozen.get(u["id"], {}).get("config_frozen") else tr("no"))] for u in self.cat.units]
        return f'<section><h2>{_e(tr("Units under test"))}</h2>{self._table([_e(tr("Unit")), _e(tr("Role")), _e(tr("Notes")), _e(tr("Configuration frozen"))], rows)}</section>'

    def _phases(self) -> str:
        from . import bench
        out = [f'<section><h2>{_e(tr("Phases, gates and bench order"))}</h2><p class="muted">{_e(tr("Within a phase, tests that use the same instrument run one after the other; dependencies always come first (SRS-DVT-196)."))}</p>']
        for p in sorted(self.cat.phases, key=lambda p: p["id"]):
            out.append(f'<h3>{_e(tr("Phase"))} {p["id"]} — {_e(p["name"])}</h3><p><b>{_e(tr("Gate"))}:</b> {_e(p.get("gate") or "—")}</p>')
            if p.get("tests"):
                rows = [["🔧 " + (_e(", ".join(sorted(tr(i) for i in g.instruments))) if g.instruments else _e(tr("No instrument"))),
                         " → ".join(_ltr(t) for t in g.tests)] for g in bench.bench_groups(self.cat, p)]
                out.append(self._table([_e(tr("Bench setup")), _e(tr("Tests, in order"))], rows, "bench"))
        return "".join(out) + "</section>"

    def _thresholds(self) -> str:
        out = [f'<section><h2>{_e(tr("Thresholds"))}</h2><p class="muted">{_e(tr("A null value is a CONFIRM item: the tests that use it report BLOCKED until it is decided."))}</p>']
        for block, vals in self.cat.thresholds.items():
            if not vals: continue
            rows = [[_ltr(k), (_ltr(v) if v is not None else f'<span class="confirm">CONFIRM</span>')] for k, v in vals.items()]
            out.append(f"<h3>{_ltr(block)}</h3>" + self._table([_e(tr("Parameter")), _e(tr("Value"))], rows))
        return "".join(out) + "</section>"

    def _status(self) -> str:
        prog = self.eng.progress(); m = self.eng.unit_matrix()
        out = [f'<section><h2>{_e(tr("Campaign status"))}</h2>']
        out.append(f'<p><b>{_e(tr("Progress"))}:</b> {prog["done"]}/{prog["total"]} · PASS {prog["PASS"]} · FAIL {prog["FAIL"]} · BLOCKED {prog["BLOCKED"]} · WAIVED {prog["WAIVED"]} · {_e(tr("open NCRs"))} {prog["openNcrs"]}</p>')
        rows = [[_ltr(u), str(d["phase"]), f'{d["done"]} / {d["total"]}'] for u, d in prog["perUnit"].items()]
        out.append(self._table([_e(tr("Unit")), _e(tr("Phase")), _e(tr("Done / owed"))], rows))
        out.append(f'<h3>{_e(tr("Verdict per test and machine"))}</h3>')
        rows = [[_ltr(r["testId"]), _e(r["title"][:60])] + [f'<span class="v v-{_e(r["cells"][u])}">{_e(r["cells"][u])}</span>' for u in m["units"]] for r in m["rows"]]
        out.append(self._table([_e(tr("Test")), _e(tr("Title"))] + [_ltr(u) for u in m["units"]], rows, "matrix"))
        ncrs = self.store.ncrs()
        if ncrs:
            out.append(f'<h3>{_e(tr("Non-conformances"))}</h3>' + self._table(["NCR", _e(tr("Run")), _e(tr("Description")), _e(tr("Disposition"))],
                       [[_ltr(n["ncr_id"]), _ltr(n["run_id"]), _e(n["description"]), _e(n["disposition"] or tr("open"))] for n in ncrs]))
        w = self.store.waivers()
        if w:
            out.append(f'<h3>{_e(tr("Waivers"))}</h3>' + self._table([_e(tr("Run")), _e(tr("Approver")), _e(tr("Rationale"))], [[_ltr(x["run_id"]), _e(x["approver"]), _e(x["rationale"])] for x in w]))
        from . import tempstats
        stats = tempstats.collect(self.cat, self.store)
        if stats:
            units = self.cat.unit_ids()
            out.append(f'<h3>{_e(tr("Temperature by component — machine comparison"))}</h3>')
            rows = []
            for fs in stats:
                cells = [f'{fs.per_unit[u].mean:.1f} ± {fs.per_unit[u].std:.1f}' if u in fs.per_unit else "—" for u in units]
                rows.append([_e(tr(tempstats.COMPONENT_LABEL.get(fs.component, fs.component))), _ltr(fs.test_id), _ltr(fs.field)] + cells + [f"{fs.between_std:.2f}", f"{fs.spread:.1f}", _ltr(", ".join(fs.outliers)) or "—"])
            out.append(self._table([_e(tr("Component")), _e(tr("Test")), _e(tr("Field"))] + [_ltr(u) for u in units] + [_e(tr("Between-unit std")), _e(tr("Spread")), _e(tr("Outlier"))], rows, "matrix"))
        return "".join(out) + "</section>"

    def _test(self, tid: str, confirms: list[str]) -> str:
        from . import bench, figures
        t = self.cat.tests[tid]; app = t["applicability"]
        p = self.cat.phase_of(tid)
        meta = [(tr("Subsystem"), self.cat.label("subsystems", t["subsystem"])), (tr("Method"), self.cat.label("methods", t["method"])), (tr("Phase"), f'{p["id"]} — {p["name"]}'),
                (tr("Applicability"), self.cat.label("rules", app["rule"]) + (f' ({app.get("unit") or "CONFIRM"})' if app["rule"] == "SINGLE" else f' ({", ".join(app.get("units") or [])})' if app["rule"] == "SUBSET" else "")),
                (tr("Repetitions"), str(t.get("repetitions") or 1)), (tr("Estimated (min)"), str(t.get("duration_est_min") if t.get("duration_est_min") is not None else "—")),
                (tr("Dependencies"), ", ".join(t.get("dependencies") or []) or tr("none")), (tr("Requirements"), ", ".join(f"REQ-{r}" for r in t.get("requirement_ids") or []) or tr("— (VCRM pending)")),
                (tr("Bench setup"), ", ".join(sorted(tr(i) for i in bench.instruments_of(t))) or tr("No instrument"))]
        out = [f'<section class="test" id="{tid}"><h2>{_ltr(tid)} — {_e(t["title"])}</h2>']
        out.append('<div class="meta">' + "".join(f'<div><span>{_e(k)}</span><b>{_ltr(v) if k in (tr("Dependencies"), tr("Requirements")) else _e(v)}</b></div>' for k, v in meta) + "</div>")
        if figures.has_figure(tid):
            try:
                out.append(f'<figure>{figures.figure_svg(tid, None, tid)}<figcaption>{_e(figures.figure_caption(tid))}</figcaption></figure>')
            except Exception:  # noqa: BLE001 - a figure must never block the document
                pass
        out.append(f'<h4>{_e(tr("Purpose"))}</h4><p>{_e((t.get("purpose") or "").strip())}</p>')
        if t.get("sample_rationale"):
            out.append(f'<h4>{_e(tr("Why this sample"))}</h4><p>{_e(t["sample_rationale"].strip())}</p>')
        if t.get("safety_plan"):
            out.append(f'<h4>{_e(tr("Safety plan"))}</h4><ul class="warn">' + "".join(f"<li>{_e(s)}</li>" for s in t["safety_plan"]) + "</ul>")
        if t.get("sweep"):
            keys = list(t["sweep"]["matrix"][0].keys())
            out.append(f'<h4>{_e(tr("Sweep"))}</h4>' + self._table([_ltr(k) for k in keys], [[_ltr(row.get(k)) for k in keys] for row in t["sweep"]["matrix"]]))
        if t.get("case_matrix"):
            out.append(f'<h4>{_e(tr("Cases"))}</h4>' + self._table([_e(tr("Case")), _e(tr("Description"))], [[_ltr(c["case"]), _e(c.get("description") or "")] for c in t["case_matrix"]]))
        if t.get("equipment"):
            out.append(f'<h4>{_e(tr("Equipment"))}</h4><ul>' + "".join(f'<li>{_e(self.cat.equipment_label(e))}' + (f' <span class="muted">({_e(tr("calibration"))}: {_ltr(e.get("calibration_id") or "CONFIRM")})</span>' if "calibration_id" in e else "") + "</li>" for e in t["equipment"]) + "</ul>")
        if t.get("preconditions"):
            out.append(f'<h4>{_e(tr("Preconditions"))}</h4><ul class="check">' + "".join(f"<li>{_e(s)}</li>" for s in t["preconditions"]) + "</ul>")
        steps = t.get("procedure_steps") or []
        if steps:
            out.append(f'<h4>{_e(tr("Procedure"))}</h4>' + self._table([_e(tr("Step")), _e(tr("Instruction")), _e(tr("Records"))],
                       [[str(i + 1), _e(s["step"]), ", ".join(_ltr(c) for c in s.get("capture") or []) or "—"] for i, s in enumerate(steps)], "steps"))
        fields = t.get("data_fields") or []
        if fields:
            out.append(f'<h4>{_e(tr("Data fields"))}</h4>' + self._table([_e(tr("Field")), _e(tr("Unit")), _e(tr("Type")), _e(tr("Range")), _e(tr("Note"))],
                       [[_ltr(f["name"]), _ltr(f.get("unit") or ""), _ltr(f["type"] + (f' [{", ".join(map(str, f.get("values") or []))}]' if f["type"] == "enum" else "")),
                         _ltr(f'{f["range"][0]}–{f["range"][1]}' if f.get("range") else ""), _e(f.get("note") or "")] for f in fields], "fields"))
        out.append(f'<h4>{_e(tr("Pass criteria"))}</h4><pre dir="ltr">{_e(t["pass_criteria"].strip())}</pre>')
        if confirms:
            out.append(f'<h4>{_e(tr("Open items (CONFIRM)"))}</h4><ul class="confirm">' + "".join(f'<li dir="ltr">{_e(c)}</li>' for c in confirms) + "</ul>")
        runs = [r for r in self.store.runs(tid) if r["status"] != "NOT_STARTED"]
        out.append(f'<h4>{_e(tr("Results so far"))}</h4>')
        if runs:
            rows = []
            for r in runs:
                vals = self.store.values(r["run_id"])
                rows.append([_ltr(r["unit_id"]), _ltr(", ".join(f"{k}={v}" for k, v in r["variant"].items()) or "—"), str(r["repetition"]), _e(r["status"]),
                             f'<span class="v v-{_e(r["verdict"] or "")}">{_e(r["verdict"] or "—")}</span>', _ltr("; ".join(f"{k}={v}" for k, v in vals.items())[:300])])
            out.append(self._table([_e(tr("Unit")), _e(tr("Variant")), _e(tr("Rep")), _e(tr("Status")), _e(tr("Verdict")), _e(tr("Values"))], rows, "runs"))
        else:
            out.append(f'<p class="muted">{_e(tr("no runs yet"))}</p>')
        return "".join(out) + "</section>"

    def _open_items(self, confirms: dict[str, list[str]]) -> str:
        out = [f'<section><h2>{_e(tr("Open items (CONFIRM)"))}</h2>']
        total = sum(len(v) for v in confirms.values())
        out.append(f'<p class="muted">{trf("{n} decisions still open in the catalog", n=total)}</p>')
        for key in [""] + [t for t in self.cat.ordered_test_ids() if t in confirms]:
            if key not in confirms: continue
            out.append(f'<h4>{_ltr(key) if key else _e(tr("Catalog header (units, thresholds)"))}</h4><ul class="confirm">' + "".join(f'<li dir="ltr">{_e(c)}</li>' for c in confirms[key]) + "</ul>")
        return "".join(out) + "</section>"

    # ------------------------------------------------------------------ document
